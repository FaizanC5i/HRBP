export const getMarketMetrics = () => {
  const opportunities = marketOpportunities;
  
  // Biggest Opportunities Index (average of top 5 priority scores * 100)
  const sortedByPriority = [...opportunities].sort((a, b) => b.priorityScore - a.priorityScore);
  const top5Avg = sortedByPriority.slice(0, 5).reduce((sum, o) => sum + o.priorityScore, 0) / 5;
  const biggestOpportunitiesIndex = Math.round(top5Avg * 100);
  
  // Acceleration breakdown
  const accelerationBreakdown = {
    rapid: opportunities.filter(o => o.accelerationStatus === 'Rapid').length,
    moderate: opportunities.filter(o => o.accelerationStatus === 'Moderate').length,
    slow: opportunities.filter(o => o.accelerationStatus === 'Slow').length,
    stable: opportunities.filter(o => o.accelerationStatus === 'Stable').length
  };
  const accelerationScore = Math.round(
    ((accelerationBreakdown.rapid * 1 + accelerationBreakdown.moderate * 0.6) / opportunities.length) * 100
  );
  
  // Risk exposure
  const riskBreakdown = {
    high: opportunities.filter(o => o.riskIfNotActing === 'High').length,
    medium: opportunities.filter(o => o.riskIfNotActing === 'Medium').length,
    low: opportunities.filter(o => o.riskIfNotActing === 'Low').length
  };
  const riskScore = Math.round(
    ((riskBreakdown.high * 1 + riskBreakdown.medium * 0.5 + riskBreakdown.low * 0.2) / opportunities.length) * 100
  );
  
  // Investment mix
  const investmentMix = {
    invest: opportunities.filter(o => o.investmentRecommendation === 'Invest').length,
    shift: opportunities.filter(o => o.investmentRecommendation === 'Shift').length,
    stop: opportunities.filter(o => o.investmentRecommendation === 'Stop').length,
    accelerate: opportunities.filter(o => o.investmentRecommendation === 'Accelerate').length
  };
  
  // Organizational actions
  const actionCounts = {
    skills: opportunities.filter(o => o.organizationalActions.skills).length,
    process: opportunities.filter(o => o.organizationalActions.process).length,
    tech: opportunities.filter(o => o.organizationalActions.tech).length,
    governance: opportunities.filter(o => o.organizationalActions.governance).length,
    partnerships: opportunities.filter(o => o.organizationalActions.partnerships).length
  };
  const actionPercentages = {
    skills: Math.round((actionCounts.skills / opportunities.length) * 100),
    process: Math.round((actionCounts.process / opportunities.length) * 100),
    tech: Math.round((actionCounts.tech / opportunities.length) * 100),
    governance: Math.round((actionCounts.governance / opportunities.length) * 100),
    partnerships: Math.round((actionCounts.partnerships / opportunities.length) * 100)
  };
  
  // Average confidence
  const avgConfidence = opportunities.reduce((sum, o) => sum + o.confidenceScore, 0) / opportunities.length;
  
  // Priority breakdown
  const priorityBreakdown = {
    high: opportunities.filter(o => o.priorityCategory === 'High').length,
    medium: opportunities.filter(o => o.priorityCategory === 'Medium').length,
    low: opportunities.filter(o => o.priorityCategory === 'Low').length,
    critical: opportunities.filter(o => o.priorityCategory === 'Critical').length
  };

  // Count unique role transitions
  const allTransitions = opportunities.flatMap(o => o.rolesToBeTransitionedTo);
  const uniqueTransitions = [...new Set(allTransitions)];
  
  return {
    biggestOpportunitiesIndex,
    accelerationScore,
    accelerationBreakdown,
    riskScore,
    riskBreakdown,
    investmentMix,
    actionCounts,
    actionPercentages,
    avgConfidence: Math.round(avgConfidence * 100),
    totalOpportunities: opportunities.length,
    priorityBreakdown,
    totalRoleTransitions: uniqueTransitions.length
  };
};
